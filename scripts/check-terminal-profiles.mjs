import assert from 'node:assert/strict';
import { terminalLaunchProfiles, terminalDefaultProfiles } from '../packages/ui/src/terminal-profiles.ts';
const providers = terminalDefaultProfiles().filter(p => p.providerId).map(p => ({id: p.providerId, enabled: true, authStatus: 'connected', defaultModelId: p.providerId === 'ollama' ? 'local-model:8b' : undefined}));
const connected = terminalLaunchProfiles([], providers, []);
assert.equal(connected.length, 9);
assert.ok(connected.every(p => p.readiness === 'ready'));
assert.deepEqual(connected.find(p => p.id === 'ollama').args, ['run', 'local-model:8b']);
const disconnected = terminalLaunchProfiles([], [], []);
assert.equal(disconnected.find(p => p.id === 'shell').readiness, 'ready');
assert.ok(disconnected.filter(p => p.id !== 'shell').every(p => p.readiness === 'blocked' && p.launchUnavailableReason === 'Not connected'));
assert.ok(terminalLaunchProfiles(disconnected, providers, []).every(p => p.readiness === 'ready'));
const revoked = terminalLaunchProfiles([], providers, [{id: 'openai', signInRejectedAt: 'today'}]);
assert.equal(revoked.find(p => p.id === 'codex').launchUnavailableReason, 'Not connected');
const saved = [{id: 'claude', displayName: 'My Claude', command: '/custom/claude', args: ['--verbose'], readiness: 'waiting'}, {id: 'ollama', command: 'ollama-api', args: [], providerId: 'ollama'}];
const migrated = terminalLaunchProfiles(saved, providers, []);
assert.equal(migrated.filter(p => p.providerId === 'anthropic').length, 1);
assert.equal(migrated[0].command, '/custom/claude');
assert.deepEqual(migrated[0].args, ['--verbose']);
assert.equal(migrated[0].readiness, 'ready');
assert.equal(migrated[1].command, 'ollama');
assert.deepEqual(migrated[1].args, ['run', 'local-model:8b']);
const noModel = terminalLaunchProfiles([], providers.map(p => ({...p, defaultModelId: undefined})), []);
assert.equal(noModel.find(p => p.id === 'ollama').launchUnavailableReason, 'Choose a model');
assert.equal(terminalLaunchProfiles([], providers, [{id: 'openai', healthCheckedAt: 'today', connectionStatus: 'disconnected'}]).find(p => p.id === 'codex').launchUnavailableReason, 'Not connected');
console.log('Terminal connection gates and launch commands passed');
