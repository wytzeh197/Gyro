import {
  beginChatPointerDrag,
  currentChatDrag,
  endChatDrag,
  subscribeChatDrag,
  type ActiveChatDrag,
  type ChatDragPayload,
} from "./chat-session-drag.ts";

export type ChatPointerPoint = Readonly<{ x: number; y: number }>;
export type ChatPointerDropTarget = Readonly<{
  element: HTMLElement;
  hover: (drag: ActiveChatDrag, point: ChatPointerPoint) => void;
  drop: (drag: ActiveChatDrag, point: ChatPointerPoint) => void;
  leave: () => void;
}>;

const DRAG_THRESHOLD = 6;
const DRAG_CLASS = "gyro-chat-pointer-dragging";
const targets = new Set<ChatPointerDropTarget>();

type PointerGesture = {
  source: HTMLElement;
  window: Window;
  document: Document;
  pointerId: number;
  origin: ChatPointerPoint;
  payload: ChatDragPayload;
  drag?: ActiveChatDrag;
  hovered?: ChatPointerDropTarget;
  cleanups: (() => void)[];
  finishing: boolean;
};

let gesture: PointerGesture | undefined;
let clearClickGuard: (() => void) | undefined;

/** Register a mounted grid; geometry remains authoritative under pointer capture. */
export function registerChatPointerDropTarget(target: ChatPointerDropTarget) {
  targets.add(target);
  return () => {
    if (!targets.delete(target)) return;
    if (gesture?.hovered === target) leaveTarget(gesture);
  };
}

export function isChatPointerDragActive() {
  return !!gesture?.drag;
}

function leaveTarget(active: PointerGesture) {
  const target = active.hovered;
  active.hovered = undefined;
  try {
    target?.leave();
  } catch {
    // An unmounted grid must not strand capture or the other lifecycle cleanup.
  }
}

function targetAt(active: PointerGesture, point: ChatPointerPoint) {
  // Pointer capture retargets events to the source. The actual painted hit
  // still tells us whether a modal or another surface covers the grid.
  const hit = active.document.elementFromPoint(point.x, point.y);
  if (!hit) return undefined;
  // The last mounted target wins if two grid rectangles temporarily overlap.
  for (const target of Array.from(targets).reverse()) {
    const element = target.element;
    if (
      !element.isConnected ||
      element.ownerDocument !== active.document ||
      element.hidden ||
      !element.contains(hit) ||
      !element.getClientRects().length
    )
      continue;
    const style = active.window.getComputedStyle(element);
    if (
      style.display === "none" ||
      style.visibility === "hidden" ||
      style.visibility === "collapse"
    )
      continue;
    const bounds = element.getBoundingClientRect();
    if (
      bounds.width > 0 &&
      bounds.height > 0 &&
      point.x >= bounds.left &&
      point.x < bounds.right &&
      point.y >= bounds.top &&
      point.y < bounds.bottom
    )
      return target;
  }
  return undefined;
}

function hoverAt(active: PointerGesture, point: ChatPointerPoint) {
  const target = targetAt(active, point);
  if (target !== active.hovered) {
    leaveTarget(active);
    active.hovered = target;
  }
  if (target && active.drag) target.hover(active.drag, point);
  return target;
}

/** Keep a completed drag's synthesized click from selecting its old source. */
function guardClick(active: PointerGesture, released: boolean) {
  clearClickGuard?.();
  const win = active.window;
  let timer: ReturnType<typeof setTimeout> | undefined;
  const clear = () => {
    if (timer !== undefined) clearTimeout(timer);
    win.removeEventListener("click", click, { capture: true });
    win.removeEventListener("pointerdown", clear, { capture: true });
    win.removeEventListener("pointerup", release, { capture: true });
    win.removeEventListener("pointercancel", release, { capture: true });
    if (clearClickGuard === clear) clearClickGuard = undefined;
  };
  const click = (event: MouseEvent) => {
    // Keyboard activation is not the mouse click generated by this gesture.
    if (event.detail === 0) return;
    const pointerId = (event as PointerEvent).pointerId;
    if (pointerId !== undefined && pointerId !== active.pointerId) return;
    event.preventDefault();
    event.stopImmediatePropagation();
    clear();
  };
  const release = (event: PointerEvent) => {
    if (event.pointerId !== active.pointerId) return;
    if (timer !== undefined) clearTimeout(timer);
    // Browsers dispatch the click in the same release turn.
    timer = setTimeout(clear, 0);
  };
  clearClickGuard = clear;
  win.addEventListener("click", click, { capture: true });
  win.addEventListener("pointerdown", clear, { capture: true });
  if (!released) {
    win.addEventListener("pointerup", release, { capture: true });
    win.addEventListener("pointercancel", release, { capture: true });
  }
  // A release or a fresh press normally clears this guard immediately. Bound
  // cancellations where the window never receives the matching release.
  timer = setTimeout(clear, released ? 0 : 5_000);
}

function finish(active: PointerGesture, released = false) {
  if (gesture !== active) return;
  gesture = undefined;
  active.finishing = true;
  for (const cleanup of active.cleanups.splice(0)) cleanup();
  leaveTarget(active);
  active.document.documentElement.classList.remove(DRAG_CLASS);
  try {
    if (active.source.hasPointerCapture(active.pointerId))
      active.source.releasePointerCapture(active.pointerId);
  } catch {
    // Source removal can release capture before our observer runs.
  }
  if (active.drag) {
    guardClick(active, released);
    endChatDrag(active.drag.dragId);
  }
}

/** Mouse-only chat transport; an ordinary press keeps native click and focus. */
export function startChatPointerDrag(
  event: PointerEvent,
  source: HTMLElement,
  payload: ChatDragPayload,
) {
  if (
    event.button !== 0 ||
    event.pointerType !== "mouse" ||
    !event.isPrimary ||
    event.defaultPrevented ||
    !source.isConnected
  )
    return;
  const doc = source.ownerDocument;
  const win = doc.defaultView;
  if (!win) return;
  if (gesture) finish(gesture);
  clearClickGuard?.();
  const active: PointerGesture = {
    source,
    window: win,
    document: doc,
    pointerId: event.pointerId,
    origin: { x: event.clientX, y: event.clientY },
    payload: Object.freeze({ ...payload }),
    cleanups: [],
    finishing: false,
  };
  gesture = active;
  const listen = (
    target: EventTarget,
    type: string,
    listener: EventListener,
  ) => {
    target.addEventListener(type, listener, { capture: true });
    active.cleanups.push(() =>
      target.removeEventListener(type, listener, { capture: true }),
    );
  };
  const cancel = () => finish(active);
  const activate = (point: ChatPointerPoint) => {
    if (active.drag) return true;
    const dx = point.x - active.origin.x;
    const dy = point.y - active.origin.y;
    if (dx * dx + dy * dy < DRAG_THRESHOLD * DRAG_THRESHOLD) return false;
    active.drag = beginChatPointerDrag(active.payload);
    if (!active.drag || currentChatDrag() !== active.drag) {
      finish(active);
      return false;
    }
    doc.documentElement.classList.add(DRAG_CLASS);
    try {
      source.setPointerCapture(active.pointerId);
    } catch {
      // A synthetic event or a very fast release can lack a native pointer.
      // Window listeners still deliver the gesture within this renderer.
    }
    return true;
  };
  const move = (moveEvent: PointerEvent) => {
    if (moveEvent.pointerId !== active.pointerId || gesture !== active) return;
    // WKWebView can report buttons:0 while the primary press is still held.
    // Its matching release, cancellation, or capture loss ends this gesture.
    if (!source.isConnected) {
      finish(active);
      return;
    }
    const point = { x: moveEvent.clientX, y: moveEvent.clientY };
    if (!activate(point)) return;
    moveEvent.preventDefault();
    try {
      hoverAt(active, point);
    } catch {
      finish(active);
    }
  };
  const release = (upEvent: PointerEvent) => {
    if (upEvent.pointerId !== active.pointerId || gesture !== active) return;
    const point = { x: upEvent.clientX, y: upEvent.clientY };
    if (!source.isConnected || !activate(point) || !active.drag) {
      finish(active, true);
      return;
    }
    upEvent.preventDefault();
    active.finishing = true;
    try {
      const target = hoverAt(active, point);
      // Final hover can update or detach a target; never commit to stale DOM.
      if (
        target &&
        targets.has(target) &&
        targetAt(active, point) === target &&
        currentChatDrag() === active.drag
      )
        target.drop(active.drag, point);
    } finally {
      finish(active, true);
    }
  };
  listen(win, "pointermove", move as EventListener);
  listen(win, "pointerup", release as EventListener);
  listen(win, "pointercancel", ((cancelEvent: PointerEvent) => {
    if (cancelEvent.pointerId === active.pointerId) finish(active, true);
  }) as EventListener);
  listen(source, "lostpointercapture", ((lostEvent: PointerEvent) => {
    if (lostEvent.pointerId === active.pointerId) cancel();
  }) as EventListener);
  listen(win, "dragstart", ((dragEvent: DragEvent) => {
    // Prevent native WebKit handoff even before our activation threshold.
    dragEvent.preventDefault();
    dragEvent.stopImmediatePropagation();
  }) as EventListener);
  for (const type of ["dragenter", "dragover", "drop", "dragend"]) {
    listen(win, type, (nativeEvent: Event) => {
      if (!active.drag) return;
      // Late native events may still carry readable bytes from an older drag.
      // The pointer release is the sole commit while this transport owns it.
      nativeEvent.preventDefault();
      nativeEvent.stopImmediatePropagation();
    });
  }
  listen(win, "keydown", ((keyEvent: KeyboardEvent) => {
    if (keyEvent.key === "Escape") cancel();
  }) as EventListener);
  listen(win, "blur", (blurEvent: Event) => {
    // Focus changes emit non-bubbling element blur through window capture.
    // Only losing the renderer window cancels the pointer gesture.
    if (blurEvent.target === win) cancel();
  });
  listen(win, "pagehide", cancel);
  listen(doc, "visibilitychange", () => {
    if (doc.visibilityState === "hidden") cancel();
  });
  active.cleanups.push(
    subscribeChatDrag((drag) => {
      if (
        active.drag &&
        !active.finishing &&
        drag?.dragId !== active.drag.dragId
      )
        cancel();
    }),
  );
  const observer = new MutationObserver(() => {
    if (!source.isConnected) cancel();
  });
  observer.observe(doc.documentElement, { childList: true, subtree: true });
  active.cleanups.push(() => observer.disconnect());
}
