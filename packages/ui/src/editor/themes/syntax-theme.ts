export function createSyntaxTheme(mode: "dark" | "light"): GyroSyntaxTheme {
  const palette = palettes[mode];
  const result = Object.fromEntries(
    tokenRoles.map((role) => [role, palette.foreground]),
  ) as GyroSyntaxTheme;
  for (const [family, roles] of Object.entries(families))
    for (const role of roles)
      result[role] = palette[family as keyof typeof palette];
  return result;
}
